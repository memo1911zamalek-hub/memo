const categoryNames = {guess:"خمن اللاعب",transfer:"انتقالات اللاعب",general:"معلومات عامة"};
const levelNames = {easy:"سهل",medium:"متوسط",hard:"صعب"};
let selectedCategory="all", selectedLevel="all", roundQuestions=[], current=0, score=0, correct=0, timerId=null, seconds=20, answered=false;

const $ = id => document.getElementById(id);
$("total-count").textContent = QUESTIONS.length + "+";
document.querySelectorAll("[data-category]").forEach(btn=>btn.addEventListener("click",()=>{
  document.querySelectorAll("[data-category]").forEach(x=>x.classList.remove("active"));
  btn.classList.add("active"); selectedCategory=btn.dataset.category;
}));
document.querySelectorAll("[data-level]").forEach(btn=>btn.addEventListener("click",()=>{
  document.querySelectorAll("[data-level]").forEach(x=>x.classList.remove("active"));
  btn.classList.add("active"); selectedLevel=btn.dataset.level;
}));
$("start-btn").addEventListener("click",startGame);
$("play-again").addEventListener("click",()=>{ $("result-panel").classList.add("hidden"); $("game-panel").classList.remove("hidden"); startGame(); });
$("next-btn").addEventListener("click",nextQuestion);

function shuffle(list){const a=[...list];for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;}
function startGame(){
  let pool=QUESTIONS.filter(q=>(selectedCategory==="all"||q.category===selectedCategory)&&(selectedLevel==="all"||q.level===selectedLevel));
  if(!pool.length){alert("لا توجد أسئلة بهذا الاختيار.");return;}
  const size=$("round-size").value;
  roundQuestions=shuffle(pool).slice(0,size==="all"?pool.length:Number(size));
  current=0;score=0;correct=0;
  $("score").textContent=score;$("game-panel").classList.add("hidden");$("result-panel").classList.add("hidden");$("quiz-panel").classList.remove("hidden");
  renderQuestion();
  $("quiz-panel").scrollIntoView({behavior:"smooth",block:"start"});
}
function renderQuestion(){
  clearInterval(timerId);answered=false;seconds=20;
  const q=roundQuestions[current];
  $("question-number").textContent=current+1;$("question-total").textContent=roundQuestions.length;
  $("progress-fill").style.width=(current/roundQuestions.length*100)+"%";
  $("category-name").textContent=categoryNames[q.category];
  $("level-label").textContent=levelNames[q.level];$("level-label").className="level-pill "+q.level;
  $("question-text").textContent=q.question;$("timer").textContent=seconds;
  $("feedback").classList.add("hidden");$("next-btn").disabled=true;
  const correctText=q.options[q.answer];
  const options=shuffle(q.options.map((text,index)=>({text,correct:index===q.answer})));
  const grid=$("answers-grid");grid.innerHTML="";
  options.forEach((option,index)=>{
    const button=document.createElement("button");button.className="answer";
    const letter=document.createElement("span");letter.className="letter";letter.textContent=["أ","ب","ج","د"][index];
    button.append(letter,document.createTextNode(option.text));
    button.addEventListener("click",()=>chooseAnswer(button,option,options));
    grid.appendChild(button);
  });
  timerId=setInterval(()=>{seconds--;$("timer").textContent=seconds;if(seconds<=0){clearInterval(timerId);timeUp();}},1000);
}
function chooseAnswer(button,option,options){
  if(answered)return;answered=true;clearInterval(timerId);
  const q=roundQuestions[current];
  document.querySelectorAll(".answer").forEach((el,i)=>{el.disabled=true;if(options[i].correct)el.classList.add("correct");});
  if(option.correct){correct++;score+=100+seconds*2;$("feedback").innerHTML="<strong>إجابة صحيحة! ممتاز ⚽</strong><br>"+q.explanation;}
  else{$("feedback").innerHTML="<strong>ليست الإجابة الصحيحة.</strong><br>الإجابة: "+q.options[q.answer]+". "+q.explanation;button.classList.add("wrong");}
  $("score").textContent=score;$("feedback").classList.remove("hidden");$("next-btn").disabled=false;
}
function timeUp(){
  if(answered)return;answered=true;
  const q=roundQuestions[current];
  document.querySelectorAll(".answer").forEach(el=>el.disabled=true);
  $("feedback").innerHTML="<strong>انتهى الوقت!</strong><br>الإجابة الصحيحة: "+q.options[q.answer]+". "+q.explanation;
  $("feedback").classList.remove("hidden");$("next-btn").disabled=false;
}
function nextQuestion(){if(!answered)return;current++;if(current>=roundQuestions.length){showResults();return;}renderQuestion();}
function showResults(){
  clearInterval(timerId);$("quiz-panel").classList.add("hidden");$("result-panel").classList.remove("hidden");
  const pct=Math.round(correct/roundQuestions.length*100);
  $("final-score").textContent=score;$("correct-count").textContent=correct+"/"+roundQuestions.length;$("accuracy").textContent=pct+"%";
  let title="بداية قوية!",message="واصل اللعب وستصبح خبيرًا في كرة القدم.",medal="⚽";
  if(pct>=90){title="أنت أسطورة كروية!";message="أداء عالمي! معلوماتك الكروية مذهلة.";medal="🏆";}
  else if(pct>=70){title="لاعب محترف!";message="نتيجة ممتازة، أنت قريب من القمة.";medal="🥇";}
  else if(pct>=50){title="أداء جيد!";message="لديك معرفة جيدة، واصل تطويرها.";medal="🥈";}
  $("result-title").textContent=title;$("result-message").textContent=message;$("result-medal").textContent=medal;
  $("result-panel").scrollIntoView({behavior:"smooth",block:"center"});
}
